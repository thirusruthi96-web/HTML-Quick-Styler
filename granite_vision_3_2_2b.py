"""SECTION DETECTION"""

def detect_sections(text):
    text = text.lower()

    sections = []

    if "hero" in text or "landing" in text:
        sections.append("hero")

    if "portfolio" in text or "gallery" in text:
        sections.append("portfolio")

    if "about" in text:
        sections.append("about")

    if "service" in text or "feature" in text:
        sections.append("services")

    if "testimonial" in text:
        sections.append("testimonials")

    if "team" in text:
        sections.append("team")

    if "pricing" in text:
        sections.append("pricing")

    if "contact" in text:
        sections.append("contact")

    if not sections:
        sections = ["hero", "about", "services","testimonials","team","pricing", "contact"]

    return sections

