"""MAIN GENERATOR"""

def generate_page(title, description, palette):

    sections = detect_sections(description)

    colors = palettes[palette]

    html_sections = ""

    for sec in sections:

        if sec == "hero":
            html_sections += hero_section(title)

        if sec == "about":
            html_sections += about_section()

        if sec == "services":
            html_sections += services_section()

        if sec == "portfolio":
            html_sections += portfolio_section()

        if sec == "testimonials":
            html_sections += testimonial_section()

        if sec == "team":
            html_sections += team_section()

        if sec == "pricing":
            html_sections += pricing_section()

        if sec == "contact":
            html_sections += contact_section()

    css = generate_css(colors)

    html = f"""
<!DOCTYPE html>
<html>
<head>
<title>{title}</title>
<style>
{css}
</style>
</head>

<body>

{html_sections}

<footer>
<p>Generated by HTML Quick Styler | {datetime.now().year}</p>
</footer>

</body>
</html>
"""

